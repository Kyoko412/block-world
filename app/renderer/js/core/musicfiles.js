/** 取某场景的文件轨（没有就返回 null，调用方退回合成曲） */
export function fileTrackFor(id) {
  const t = FILE_TRACKS[id];
  return t && t.file ? t : null;
}

/** 同源相对 URL：`/media/music/xxx.ogg`（走本地回环服务器，绝不产生外网请求） */
export function fileUrl(entryOrId) {
  const entry = typeof entryOrId === 'string' ? fileTrackFor(entryOrId) : entryOrId;
  if (!entry || !entry.file) return null;
  return '/' + MUSIC_FILE_DIR + '/' + entry.file;
}

/** '2:14' → 134（用于把页面标注的时长和解码结果对上） */
export function parseDuration(text) {
  const m = /^(\d+):([0-5]\d)$/.exec(String(text || '').trim());
  if (!m) return null;
  return Number(m[1]) * 60 + Number(m[2]);
}

